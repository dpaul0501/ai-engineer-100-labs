"""Assemble guide/docs/week_01/*.html from shell_head.html + pages/<name>.body.html + shell_tail.html.

Run from anywhere: python guide/src/week_01/build.py
Bodies hold only the page content (what sits inside <div class="page">, before the pager).
Checkpoint ids and dimensions are collected from every body to build the progress manifest.
"""
import json, re, shutil
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parents[1] / "docs" / "week_01"

# file, rail label, rail title, <title> suffix, meta description
PAGES = [
    ("index", "R", "The problem", "The problem",
     "Week 1 reading: what People You May Know has to do, what a good suggestion is, and the plan for the week."),
    ("day_1", "D1", "Common friends", "Common friends",
     "Day 1: intersecting two friend lists, from nested loops to hash sets, merges and bitsets, then across machines and with MinHash."),
    ("day_2", "D2", "The top k", "The top k",
     "Day 2: picking the best k, from a fixed list and from a stream, and on many machines at once."),
    ("day_3", "D3", "It is a graph", "It is a graph",
     "Day 3: why friend lists form a graph, and what breadth-first search, degrees, triangles and random walks add."),
    ("day_4", "D4", "Learn what engagement means", "Learn what engagement means",
     "Day 4: from a hand-made score to a calibrated probability: labels, log loss, models, features, evaluation, A/B tests and exposure bias."),
    ("day_5", "D5", "A billion users", "A billion users",
     "Day 5: the distributed algorithms behind People You May Know at scale, and the product decisions around it."),
    ("worksheet", "WS", "Worksheet and checks", "Worksheet and checks",
     "Week 1 worksheet: the lab work items, the checks for every day, and the interview drills."),
]

RAIL_TOP = '''<nav class="rail" aria-label="Week 1">
  <div class="brand">People You May Know <span>from two friend lists to a billion users</span></div>
  <div class="rail-label">Coverage, whole week</div>
  <div class="prog" data-prog></div>
  <div class="rail-label">Week 1 · People You May Know</div>
'''
RAIL_END = '''  <a href="talk.html"><span class="n">▶</span>The talk (slides)</a>
  <a href="../"><span class="n">↩</span>Guide home</a>
</nav>
'''
FOOTER = '''<footer>
  <p><b>License.</b> This page, its text, code and figures, is licensed under the <a href="https://creativecommons.org/licenses/by/4.0/">Creative Commons Attribution 4.0 International License (CC BY 4.0)</a>. You may share and adapt it for any purpose, including commercially, if you give credit ("People You May Know, AI Engineer 100, Debjyoti Paul, CC BY 4.0"), link to the license, and note any changes.</p>
  <p><b>Third-party material.</b> No third-party text, figures or code are reproduced; papers, videos, blogs, tools and problems are linked and remain under their owners' terms. "People You May Know" is discussed as a classic interview design problem; nothing here describes any company's internal system. Measurements use a synthetic graph generated by the week's own script. Problem names refer to LeetCode problems, which are LeetCode's; solutions here are original.</p>
  <p>Part of the self-paced <a href="https://dpaul0501.github.io/ai-engineer-100-labs/">AI Engineer 100</a> guide · <a href="index.html">Week 1</a></p>
</footer>
'''

def esc(s):
    return s.replace("&", "&amp;").replace('"', "&quot;")

def main():
    head, tail = (HERE / "shell_head.html").read_text(), (HERE / "shell_tail.html").read_text()
    def body(f):
        p = HERE / "pages" / f"{f}.body.html"
        return p.read_text() if p.exists() else '<section class="s"><h2>Not written yet</h2></section>\n'
    bodies = {f: body(f) for f, *_ in PAGES}
    items, seen = [], set()
    for f, *_ in PAGES:
        for m in re.finditer(r'data-id="([^"]+)"\s+data-dim="([^"]+)"', bodies[f]):
            assert m.group(1) not in seen, f"duplicate checkpoint id {m.group(1)}"
            seen.add(m.group(1))
            items.append({"id": m.group(1), "dim": m.group(2), "page": f + ".html"})
    (OUT / "img").mkdir(parents=True, exist_ok=True)
    for img in (HERE / "img").iterdir():
        shutil.copy(img, OUT / "img" / img.name)
    for i, (f, n, rail, title, desc) in enumerate(PAGES):
        on = ' class="on"'
        links = "".join(
            f'  <a href="{g}.html"{on if g == f else ""} data-page="{g}.html"><span class="n">{gn}</span>{gr}</a>\n'
            for g, gn, gr, *_ in PAGES)
        prev = f'<a class="btn" href="{PAGES[i-1][0]}.html">← {PAGES[i-1][2]}</a>' if i else "<span></span>"
        nxt = f'<a class="btn pri" href="{PAGES[i+1][0]}.html">{PAGES[i+1][2]} →</a>' if i + 1 < len(PAGES) else "<span></span>"
        html = (head.replace("{{TITLE}}", f"People You May Know · {title}").replace("{{DESC}}", esc(desc))
                + RAIL_TOP + links + RAIL_END + '\n<main><div class="page">' + bodies[f]
                + f'<div class="pager">{prev}{nxt}</div>\n' + FOOTER + "\n</div></main>\n</div>\n"
                + tail.replace("{{ITEMS}}", json.dumps(items)))
        assert not re.search(r"\{\{[A-Z]+\}\}", html), f
        (OUT / f"{f}.html").write_text(html)
    dims = {}
    for it in items:
        dims[it["dim"]] = dims.get(it["dim"], 0) + 1
    print(len(items), "checkpoints", dims)

if __name__ == "__main__":
    main()
